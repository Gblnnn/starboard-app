-- Overlap prevention trigger
CREATE OR REPLACE FUNCTION public.htm_check_config_overlap()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.hourly_tm_employee_config c
    WHERE c.id <> COALESCE(NEW.id, -1)
      AND c.emp_id = NEW.emp_id
      AND c.project_code = NEW.project_code
      AND c.active = TRUE
      AND (c.effective_to IS NULL OR c.effective_to >= NEW.effective_from)
      AND (NEW.effective_to IS NULL OR NEW.effective_to >= c.effective_from)
  ) THEN
    RAISE EXCEPTION 'Overlapping effective-date range for emp_id=% project_code=%', NEW.emp_id, NEW.project_code;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_htm_employee_config_overlap ON public.hourly_tm_employee_config;
CREATE TRIGGER trg_htm_employee_config_overlap
  BEFORE INSERT OR UPDATE ON public.hourly_tm_employee_config
  FOR EACH ROW EXECUTE FUNCTION public.htm_check_config_overlap();

