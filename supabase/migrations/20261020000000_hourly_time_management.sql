-- ---------------------------------------------------------------------------
-- I. RPC: BULK ATTENDANCE UPSERT (atomic, blocks finalized-period edits)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.htm_bulk_upsert_attendance(
  p_records  jsonb,
  p_actor    text
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_rec         jsonb;
  v_emp_id      text;
  v_proj        text;
  v_date        date;
  v_hours       numeric(5,2);
  v_remarks     text;
  v_inserted    int := 0;
  v_updated     int := 0;
  v_locked_dates text[];
BEGIN
  IF jsonb_array_length(p_records) = 0 THEN
    RAISE EXCEPTION 'No records provided';
  END IF;

  SELECT array_agg(DISTINCT (r->>'attendance_date')::text) INTO v_locked_dates
  FROM jsonb_array_elements(p_records) r
  WHERE EXISTS (
    SELECT 1 FROM public.hourly_tm_payroll_periods pp
    WHERE pp.project_code = (r->>'project_code')
      AND pp.status = 'finalized'
      AND (r->>'attendance_date')::date BETWEEN pp.start_date AND pp.end_date
  );

  IF v_locked_dates IS NOT NULL AND array_length(v_locked_dates, 1) > 0 THEN
    RAISE EXCEPTION 'Cannot save attendance: dates % fall within a finalized payroll period', v_locked_dates;
  END IF;

  FOR v_rec IN SELECT * FROM jsonb_array_elements(p_records) LOOP
    v_emp_id  := v_rec->>'emp_id';
    v_proj    := v_rec->>'project_code';
    v_date    := (v_rec->>'attendance_date')::date;
    v_hours   := (v_rec->>'hours_worked')::numeric;
    v_remarks := v_rec->>'remarks';

    IF v_hours < 0 OR v_hours > 24 THEN
      RAISE EXCEPTION 'Invalid hours_worked=% for emp_id=% on %', v_hours, v_emp_id, v_date;
    END IF;

    INSERT INTO public.hourly_tm_attendance
      (emp_id, project_code, attendance_date, hours_worked, remarks, created_by, updated_by)
    VALUES
      (v_emp_id, v_proj, v_date, v_hours, v_remarks, p_actor, p_actor)
    ON CONFLICT (emp_id, attendance_date)
    DO UPDATE SET
      hours_worked  = EXCLUDED.hours_worked,
      project_code  = EXCLUDED.project_code,
      remarks       = EXCLUDED.remarks,
      updated_by    = p_actor,
      updated_at    = now();

    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    v_updated := v_updated + v_inserted;
  END LOOP;

  RETURN jsonb_build_object('total', jsonb_array_length(p_records), 'processed', v_updated);
END;
$$;

REVOKE ALL ON FUNCTION public.htm_bulk_upsert_attendance(jsonb, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.htm_bulk_upsert_attendance(jsonb, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- J. RPC: FINALIZE PAYROLL PERIOD
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.htm_finalize_payroll_period(
  p_period_id   bigint,
  p_snapshots   jsonb,
  p_actor       text
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_period      public.hourly_tm_payroll_periods%ROWTYPE;
  v_snap        jsonb;
  v_count       int := 0;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtext('htm_finalize_' || p_period_id::text));

  SELECT * INTO v_period FROM public.hourly_tm_payroll_periods WHERE id = p_period_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Payroll period % not found', p_period_id;
  END IF;

  IF v_period.status = 'finalized' THEN
    RAISE EXCEPTION 'Payroll period % is already finalized', p_period_id;
  END IF;

  DELETE FROM public.hourly_tm_payroll_snapshot WHERE payroll_period_id = p_period_id;

  FOR v_snap IN SELECT * FROM jsonb_array_elements(p_snapshots) LOOP
    INSERT INTO public.hourly_tm_payroll_snapshot (
      payroll_period_id, emp_id, project_code, start_date, end_date,
      pay_category, monthly_salary, hourly_rate, ot_multiplier, regular_hours,
      payable_days, total_hours_worked, total_ot_hours,
      normal_pay, ot_pay, gross_pay,
      daily_hours_json, finalized_at, finalized_by
    ) VALUES (
      p_period_id,
      v_snap->>'emp_id',
      v_snap->>'project_code',
      (v_snap->>'start_date')::date,
      (v_snap->>'end_date')::date,
      v_snap->>'pay_category',
      NULLIF(v_snap->>'monthly_salary','null')::numeric,
      NULLIF(v_snap->>'hourly_rate','null')::numeric,
      NULLIF(v_snap->>'ot_multiplier','null')::numeric,
      (v_snap->>'regular_hours')::numeric,
      (v_snap->>'payable_days')::numeric,
      (v_snap->>'total_hours_worked')::numeric,
      (v_snap->>'total_ot_hours')::numeric,
      (v_snap->>'normal_pay')::numeric,
      (v_snap->>'ot_pay')::numeric,
      (v_snap->>'gross_pay')::numeric,
      v_snap->'daily_hours_json',
      now(),
      p_actor
    );
    v_count := v_count + 1;
  END LOOP;

  UPDATE public.hourly_tm_payroll_periods
  SET status = 'finalized', finalized_at = now(), finalized_by = p_actor, updated_at = now()
  WHERE id = p_period_id;

  RETURN jsonb_build_object('period_id', p_period_id, 'lines_saved', v_count, 'finalized_by', p_actor);
END;
$$;

REVOKE ALL ON FUNCTION public.htm_finalize_payroll_period(bigint, jsonb, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.htm_finalize_payroll_period(bigint, jsonb, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- K. RPC: REOPEN PAYROLL PERIOD
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.htm_reopen_payroll_period(
  p_period_id  bigint,
  p_actor      text,
  p_reason     text
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_period public.hourly_tm_payroll_periods%ROWTYPE;
BEGIN
  SELECT * INTO v_period FROM public.hourly_tm_payroll_periods WHERE id = p_period_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Payroll period % not found', p_period_id;
  END IF;

  IF v_period.status <> 'finalized' THEN
    RAISE EXCEPTION 'Only finalized periods can be reopened. Current status: %', v_period.status;
  END IF;

  UPDATE public.hourly_tm_payroll_periods
  SET status = 'reopened', reopened_at = now(), reopened_by = p_actor,
      reopen_reason = p_reason, updated_at = now()
  WHERE id = p_period_id;

  RETURN jsonb_build_object('period_id', p_period_id, 'reopened_by', p_actor, 'reason', p_reason);
END;
$$;

