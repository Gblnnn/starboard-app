-- ---------------------------------------------------------------------------
-- J. BALANCE CALCULATION VIEW
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.v_petty_cash_balance AS
WITH assignments AS (
  SELECT id, project_code, emp_id, op_balance, op_date, active
  FROM public.pettycash_user
),
payments AS (
  SELECT
    r.project_code,
    r.emp_id,
    COALESCE(SUM(p.payment_amount), 0) AS total_funding
  FROM public.petty_cash_request r
  JOIN public.petty_cash_request_payment p ON p.request_id = r.id
  WHERE r.status IN ('approved','partially_paid','fully_paid')
  GROUP BY r.project_code, r.emp_id
),
approved_expenses AS (
  SELECT
    t.project_code,
    t.emp_id,
    COALESCE(SUM(COALESCE(t.fin_approved_amount, 0)), 0) AS total_approved_expenses
  FROM public.petty_cash_transaction t
  JOIN public.petty_cash_submission s ON s.id = t.submission_id
  WHERE s.status = 'approved'
  GROUP BY t.project_code, t.emp_id
),
pending_expenses AS (
  SELECT
    t.project_code,
    t.emp_id,
    COALESCE(SUM(t.exp_amount), 0) AS total_pending_expenses
  FROM public.petty_cash_transaction t
  JOIN public.petty_cash_submission s ON s.id = t.submission_id
  WHERE s.status IN ('draft','pending_petty_cash_approval','pending_finance_approval','returned_for_correction')
  GROUP BY t.project_code, t.emp_id
),
reimbursement_payable AS (
  -- approved expenses that exceed the opening+funding balance represent personal-funded amounts
  -- Total reimbursement payable = sum of fin_approved amounts on approved submissions
  SELECT
    t.project_code,
    t.emp_id,
    COALESCE(SUM(COALESCE(t.fin_approved_amount, 0)), 0) AS total_reimbursable
  FROM public.petty_cash_transaction t
  JOIN public.petty_cash_submission s ON s.id = t.submission_id
  WHERE s.status = 'approved'
  GROUP BY t.project_code, t.emp_id
),
reimbursement_paid AS (
  SELECT
    project_code,
    emp_id,
    COALESCE(SUM(payment_amount), 0) AS total_reimbursement_paid
  FROM public.petty_cash_reimbursement_payment
  GROUP BY project_code, emp_id
),
approved_funding_unpaid AS (
  SELECT
    r.project_code,
    r.emp_id,
    COALESCE(SUM(r.approved_amount), 0)
      - COALESCE(SUM(paid.total_paid), 0) AS awaiting_payment
  FROM public.petty_cash_request r
  LEFT JOIN (
    SELECT request_id, SUM(payment_amount) AS total_paid
    FROM public.petty_cash_request_payment
    GROUP BY request_id
  ) paid ON paid.request_id = r.id
  WHERE r.status IN ('approved','partially_paid')
  GROUP BY r.project_code, r.emp_id
)
SELECT
  a.project_code,
  a.emp_id,
  a.active,
  a.op_balance,
  COALESCE(p.total_funding, 0)                                   AS total_funding_received,
  COALESCE(ae.total_approved_expenses, 0)                        AS total_approved_expenses,
  a.op_balance
    + COALESCE(p.total_funding, 0)
    - COALESCE(ae.total_approved_expenses, 0)                    AS available_balance,
  COALESCE(pe.total_pending_expenses, 0)                         AS pending_expense_claims,
  COALESCE(rp.total_reimbursable, 0)                             AS approved_reimbursement_payable,
  COALESCE(rpd.total_reimbursement_paid, 0)                      AS reimbursement_paid,
  COALESCE(rp.total_reimbursable, 0)
    - COALESCE(rpd.total_reimbursement_paid, 0)                  AS outstanding_reimbursement,
  COALESCE(afu.awaiting_payment, 0)                              AS approved_funding_awaiting_payment
FROM assignments a
LEFT JOIN payments          p   ON p.project_code  = a.project_code AND p.emp_id  = a.emp_id
LEFT JOIN approved_expenses ae  ON ae.project_code = a.project_code AND ae.emp_id = a.emp_id
LEFT JOIN pending_expenses  pe  ON pe.project_code = a.project_code AND pe.emp_id = a.emp_id
LEFT JOIN reimbursement_payable rp  ON rp.project_code = a.project_code AND rp.emp_id = a.emp_id
LEFT JOIN reimbursement_paid    rpd ON rpd.project_code = a.project_code AND rpd.emp_id = a.emp_id
LEFT JOIN approved_funding_unpaid afu ON afu.project_code = a.project_code AND afu.emp_id = a.emp_id;

-- ---------------------------------------------------------------------------
-- K. FUNCTION: RECORD FUNDING PAYMENT (transactional, prevents overpayment)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.pc_record_funding_payment(
  p_request_id       bigint,
  p_payment_amount   numeric,
  p_payment_date     date,
  p_payment_reference text,
  p_recorded_by      text
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_request        public.petty_cash_request%ROWTYPE;
  v_total_paid     numeric(12,3);
  v_remaining      numeric(12,3);
  v_new_total_paid numeric(12,3);
  v_new_status     text;
  v_payment_id     bigint;
BEGIN
  -- Advisory lock per request to prevent concurrent overpayments
  PERFORM pg_advisory_xact_lock(hashtext('pc_payment_' || p_request_id::text));

  SELECT * INTO v_request
  FROM public.petty_cash_request
  WHERE id = p_request_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Request % not found', p_request_id;
  END IF;

  IF v_request.status NOT IN ('approved','partially_paid') THEN
    RAISE EXCEPTION 'Request % is in status % and cannot receive payments', p_request_id, v_request.status;
  END IF;

  IF v_request.approved_amount IS NULL OR v_request.approved_amount <= 0 THEN
    RAISE EXCEPTION 'Request % has no approved amount', p_request_id;
  END IF;

  SELECT COALESCE(SUM(payment_amount), 0) INTO v_total_paid
  FROM public.petty_cash_request_payment
  WHERE request_id = p_request_id;

  v_remaining := v_request.approved_amount - v_total_paid;

  IF p_payment_amount <= 0 THEN
    RAISE EXCEPTION 'Payment amount must be positive';
  END IF;

  IF p_payment_amount > v_remaining THEN
    RAISE EXCEPTION 'Payment of % exceeds outstanding approved amount of % for request %',
      p_payment_amount, v_remaining, p_request_id;
  END IF;

  INSERT INTO public.petty_cash_request_payment
    (request_id, project_code, payment_amount, payment_date, payment_reference, recorded_by)
  VALUES
    (p_request_id, v_request.project_code, p_payment_amount, p_payment_date, p_payment_reference, p_recorded_by)
  RETURNING id INTO v_payment_id;

  v_new_total_paid := v_total_paid + p_payment_amount;

  IF v_new_total_paid >= v_request.approved_amount THEN
    v_new_status := 'fully_paid';
  ELSE
    v_new_status := 'partially_paid';
  END IF;

  UPDATE public.petty_cash_request
  SET status = v_new_status, updated_at = now()
  WHERE id = p_request_id;

  RETURN jsonb_build_object(
    'payment_id',      v_payment_id,
    'status',          v_new_status,
    'total_paid',      v_new_total_paid,
    'approved_amount', v_request.approved_amount
  );
END;
$$;

REVOKE ALL ON FUNCTION public.pc_record_funding_payment(bigint,numeric,date,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pc_record_funding_payment(bigint,numeric,date,text,text) TO authenticated;

-- ---------------------------------------------------------------------------
-- L. FUNCTION: RESERVE FUEL BILLS (atomic claim on submission)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.pc_reserve_fuel_bills(
  p_submission_id bigint,
  p_fuel_log_ids  bigint[]
)
RETURNS jsonb
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  v_updated_count integer;
  v_already_claimed bigint[];
BEGIN
  -- Check for already-claimed bills
  SELECT array_agg(id) INTO v_already_claimed
  FROM public.fuel_log
  WHERE id = ANY(p_fuel_log_ids)
    AND petty_cash_submission_id IS NOT NULL
    AND petty_cash_submission_id <> p_submission_id;

  IF v_already_claimed IS NOT NULL AND array_length(v_already_claimed, 1) > 0 THEN
    RAISE EXCEPTION 'Fuel bills % are already claimed by another submission', v_already_claimed;
  END IF;

  UPDATE public.fuel_log
  SET petty_cash_submission_id = p_submission_id
  WHERE id = ANY(p_fuel_log_ids)
    AND (petty_cash_submission_id IS NULL OR petty_cash_submission_id = p_submission_id);

  GET DIAGNOSTICS v_updated_count = ROW_COUNT;

  RETURN jsonb_build_object('reserved_count', v_updated_count);
END;
$$;

