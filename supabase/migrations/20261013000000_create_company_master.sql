CREATE TABLE IF NOT EXISTS public.company_master (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  company_name text NOT NULL,
  alfa_code text NOT NULL,
  num_code bigint NOT NULL,
  CONSTRAINT "Company_Master_pkey" PRIMARY KEY (id),
  CONSTRAINT "Company_Master_Alfa_Code_key" UNIQUE (alfa_code),
  CONSTRAINT "Company_Master_Company_Name_key" UNIQUE (company_name),
  CONSTRAINT "Company_Master_Num_Code_key" UNIQUE (num_code),
  CONSTRAINT "Company_Master_Alfa_Code_format_check" CHECK (alfa_code ~ '^[A-Z]{2}$'),
  CONSTRAINT "Company_Master_Num_Code_range_check" CHECK (num_code BETWEEN 10 AND 99)
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_pkey') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_pkey" PRIMARY KEY (id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_Alfa_Code_key') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_Alfa_Code_key" UNIQUE (alfa_code);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_Company_Name_key') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_Company_Name_key" UNIQUE (company_name);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_Num_Code_key') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_Num_Code_key" UNIQUE (num_code);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_Alfa_Code_format_check') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_Alfa_Code_format_check" CHECK (alfa_code ~ '^[A-Z]{2}$');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.company_master'::regclass AND conname = 'Company_Master_Num_Code_range_check') THEN
    ALTER TABLE public.company_master ADD CONSTRAINT "Company_Master_Num_Code_range_check" CHECK (num_code BETWEEN 10 AND 99);
  END IF;
END;
$$;

ALTER TABLE public.company_master ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.company_master TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.company_master_id_seq TO authenticated;

DROP POLICY IF EXISTS "Company master authenticated read" ON public.company_master;
CREATE POLICY "Company master authenticated read"
  ON public.company_master
  FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Company master admin write" ON public.company_master;
CREATE POLICY "Company master admin write"
  ON public.company_master
  FOR ALL
  TO authenticated
  USING (
    EXISTS (
      SELECT 1
      FROM public.users AS app_user
      WHERE lower(app_user.email) = lower(auth.jwt() ->> 'email')
        AND app_user.role = 'admin'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1
      FROM public.users AS app_user
      WHERE lower(app_user.email) = lower(auth.jwt() ->> 'email')
        AND app_user.role = 'admin'
    )
  );

CREATE OR REPLACE FUNCTION public.create_company_master(p_company_name text, p_alfa_code text)
RETURNS public.company_master
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  next_code bigint;
  created_company public.company_master;
  normalized_name text := btrim(p_company_name);
  normalized_alfa_code text := upper(btrim(p_alfa_code));
BEGIN
  IF normalized_name IS NULL OR normalized_name = '' THEN
    RAISE EXCEPTION 'Company name is required';
  END IF;

  IF normalized_alfa_code IS NULL OR normalized_alfa_code !~ '^[A-Z]{2}$' THEN
    RAISE EXCEPTION 'Alpha code must contain exactly two letters';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('company_master_num_code'));

  SELECT COALESCE(MAX(num_code), 9) + 1
    INTO next_code
    FROM public.company_master
    WHERE num_code NOT IN (50, 99);

  WHILE next_code IN (50, 99)
     OR EXISTS (SELECT 1 FROM public.company_master WHERE num_code = next_code)
  LOOP
    next_code := next_code + 1;
  END LOOP;

  IF next_code > 99 THEN
    RAISE EXCEPTION 'No available two-digit company codes remain';
  END IF;

  INSERT INTO public.company_master (company_name, alfa_code, num_code)
  VALUES (normalized_name, normalized_alfa_code, next_code)
  RETURNING * INTO created_company;

  RETURN created_company;
END;
$$;

REVOKE ALL ON FUNCTION public.create_company_master(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.create_company_master(text, text) TO authenticated;
